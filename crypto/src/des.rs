fn permute(input: u64, input_bits: u32, table: &[u8]) -> u64 {
    table.iter().fold(0, |out, &position| {
        (out << 1) | ((input >> (input_bits - u32::from(position))) & 1)
    })
}

fn s_box(table: &[u8; 64], six_bits: u64) -> u64 {
    let index = ((six_bits & 0x20) | ((six_bits & 1) << 4)) | ((six_bits >> 1) & 0xf);
    table.iter().enumerate().fold(0, |found, (at, &value)| {
        let difference = at as u64 ^ index;
        let same = mask_u64(((difference | difference.wrapping_neg()) >> 63) ^ 1);
        found | (u64::from(value) & same)
    })
}

fn round_keys(key: u64) -> [u64; 16] {
    let chosen = permute(key, 64, &KEY_CHOICE_1);
    let (mut left, mut right) = (chosen >> 28, chosen & 0x0fff_ffff);
    let mut keys = [0u64; 16];
    for (slot, shift) in keys.iter_mut().zip(SHIFTS) {
        left = ((left << shift) | (left >> (28 - shift))) & 0x0fff_ffff;
        right = ((right << shift) | (right >> (28 - shift))) & 0x0fff_ffff;
        *slot = permute((left << 28) | right, 56, &KEY_CHOICE_2);
    }
    keys
}

fn feistel(half: u64, round_key: u64) -> u64 {
    let mixed = permute(half, 32, &EXPANSION) ^ round_key;
    let substituted = S_BOXES
        .iter()
        .enumerate()
        .fold(0, |out, (index, table)| {
            (out << 4) | s_box(table, (mixed >> (42 - 6 * index)) & 0x3f)
        });
    permute(substituted, 32, &PERMUTATION)
}

/// `block` encrypted under the 64-bit `key` (its parity bits ignored).
pub fn encrypt(key: &[u8; 8], block: &[u8; 8]) -> [u8; 8] {
    let keys = round_keys(u64::from_be_bytes(*key));
    let start = permute(u64::from_be_bytes(*block), 64, &INITIAL);
    let (mut left, mut right) = (start >> 32, start & 0xffff_ffff);
    for round_key in keys {
        (left, right) = (right, left ^ feistel(right, round_key));
    }
    permute((right << 32) | left, 64, &FINAL).to_be_bytes()
}

/// The DES key whose seven-bit groups are the 56 bits of `seven`, parity bits left zero.
pub fn key_from_seven(seven: &[u8; 7]) -> [u8; 8] {
    let mut wide = [0u8; 8];
    wide[1..].copy_from_slice(seven);
    let bits = u64::from_be_bytes(wide);
    let mut key = [0u8; 8];
    for (index, byte) in key.iter_mut().enumerate() {
        *byte = (((bits >> (49 - 7 * index)) & 0x7f) << 1) as u8;
    }
    key
}
