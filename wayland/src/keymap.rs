//! The keyboard map every Wayland client gets (D140): our own minimal US layout in the xkb
//! text format version 1, which `wl_keyboard.keymap` carries. Key codes are Linux's input
//! codes plus 8, as xkb counts them; Shift, Caps Lock, Control, Alt (`Mod1`) and Super
//! (`Mod4`) are the real modifiers at their usual bits.

/// Shift's bit in `wl_keyboard.modifiers`' masks.
pub const SHIFT: u32 = 1 << 0;
/// Caps Lock's bit.
pub const LOCK: u32 = 1 << 1;
/// Control's bit.
pub const CONTROL: u32 = 1 << 2;
/// Alt's bit (`Mod1`).
pub const MOD1: u32 = 1 << 3;
/// Super's bit (`Mod4`).
pub const MOD4: u32 = 1 << 6;

/// The `/dev/window` modifier bits of a `Key` record (Shift 1, Ctrl 2, Alt 4, Super 8, Caps
/// Lock 16) as `wl_keyboard.modifiers`' depressed and locked masks.
pub const fn modifier_masks(bits: u32) -> (u32, u32) {
    let mut depressed = 0;
    if bits & 1 != 0 {
        depressed |= SHIFT;
    }
    if bits & 2 != 0 {
        depressed |= CONTROL;
    }
    if bits & 4 != 0 {
        depressed |= MOD1;
    }
    if bits & 8 != 0 {
        depressed |= MOD4;
    }
    let locked = if bits & 16 != 0 { LOCK } else { 0 };
    (depressed, locked)
}

