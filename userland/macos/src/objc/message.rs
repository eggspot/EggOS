//! `objc_msgSend` and `objc_msgSendSuper2` (and x86_64's `_stret` forms, whose struct result
//! goes through a hidden first argument). The fast path loads the receiver's class and its
//! cache table, probes it as `cache.rs` describes and jumps to the IMP, touching no stack and
//! no lock; a nil receiver returns zeros. A miss saves every argument register, asks
//! [`lookup_for_send`] for the IMP and jumps to it with the registers restored, so the method
//! sees the caller's arguments, variadic ones and the x86_64 vector count in `al` included.

use super::abi::{ClassObject, Id, Imp, Sel};
use super::class;

extern "C" fn lookup_for_send(receiver: Id, sel: Sel, class: *mut ClassObject) -> Imp {
    match class::lookup(class, sel) {
        Some(imp) => imp,
        None => {
            let _ = receiver;
            not_recognized as *const () as Imp
        }
    }
}

#[cfg(target_arch = "x86_64")]
extern "C" fn lookup_for_struct_send(receiver: Id, sel: Sel, class: *mut ClassObject) -> Imp {
    match class::lookup(class, sel) {
        Some(imp) => imp,
        None => {
            let _ = receiver;
            not_recognized_struct as *const () as Imp
        }
    }
}

extern "C" fn not_recognized(receiver: Id, sel: Sel) -> usize {
    super::root::does_not_recognize(receiver, sel)
}

#[cfg(target_arch = "x86_64")]
extern "C" fn not_recognized_struct(result: usize, receiver: Id, sel: Sel) -> usize {
    super::root::does_not_recognize(receiver, sel);
    result
}

